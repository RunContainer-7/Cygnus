import { escapeHtml, headlineFromPrompt, hueFromPrompt, titleFromPrompt } from "./shared";

export function buildLandingDemo(prompt: string) {
  const brand = escapeHtml(titleFromPrompt(prompt).slice(0, 24));
  const headline = escapeHtml(headlineFromPrompt(prompt));
  const hue = hueFromPrompt(prompt);

  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${brand}</title>
  <link rel="stylesheet" href="./styles.css" />
</head>
<body>
  <header class="nav">
    <div class="brand"><span class="dot"></span>${brand}</div>
    <nav><a href="#features">Features</a><a href="#start">Get started</a></nav>
  </header>
  <main>
    <section class="hero" id="start">
      <p class="eyebrow">Sample project · built offline</p>
      <h1>${headline}</h1>
      <p class="lede">This page was generated by the Cygnus offline demo, with no model call. Connect a provider to build the real thing.</p>
      <div class="row">
        <button class="btn" id="cta">Join the waitlist</button>
        <a class="btn ghost" href="#features">See features</a>
      </div>
      <p class="note" id="note" role="status"></p>
    </section>
    <section class="cards" id="features">
      <article class="card"><h3>Instant</h3><p>Every change shows up in the preview right away, with no build step to wait on.</p></article>
      <article class="card"><h3>Responsive</h3><p>Fluid type and layout that hold together from a phone up to a wide monitor.</p></article>
      <article class="card"><h3>Yours</h3><p>Plain HTML, CSS and JavaScript in a folder you control. Export or edit it anywhere.</p></article>
    </section>
  </main>
  <footer>© 2026 ${brand} · sample project</footer>
  <script src="./app.js" defer></script>
</body>
</html>
`;

  const css = `:root {
  --hue: ${hue};
  --bg: #070a12;
  --fg: #eef2ff;
  --muted: #98a2c0;
  --line: rgba(255, 255, 255, 0.1);
  --accent: hsl(var(--hue) 95% 70%);
}
* { box-sizing: border-box; }
html { scroll-behavior: smooth; }
body {
  margin: 0;
  min-height: 100vh;
  color: var(--fg);
  font-family: Inter, ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;
  background:
    radial-gradient(900px 480px at 50% -10%, hsl(var(--hue) 85% 45% / 0.38), transparent 65%),
    var(--bg);
}
a { color: inherit; }
.nav {
  display: flex;
  align-items: center;
  justify-content: space-between;
  padding: 24px clamp(20px, 5vw, 64px);
}
.brand { display: flex; align-items: center; gap: 10px; font-weight: 650; letter-spacing: -0.02em; }
.dot { width: 10px; height: 10px; border-radius: 50%; background: var(--accent); box-shadow: 0 0 18px var(--accent); }
nav a { margin-left: 22px; color: var(--muted); font-size: 14px; text-decoration: none; }
nav a:hover { color: var(--fg); }
.hero { max-width: 860px; margin: 0 auto; padding: clamp(56px, 12vh, 130px) 24px 70px; text-align: center; }
.eyebrow { margin: 0; color: var(--accent); font-size: 12px; letter-spacing: 0.16em; text-transform: uppercase; }
h1 { margin: 18px 0; font-size: clamp(38px, 6.4vw, 74px); line-height: 1.02; letter-spacing: -0.045em; }
.lede { max-width: 600px; margin: 0 auto; color: var(--muted); font-size: clamp(15px, 1.9vw, 18px); line-height: 1.65; }
.row { display: flex; flex-wrap: wrap; gap: 12px; justify-content: center; margin-top: 34px; }
.btn {
  display: inline-flex; align-items: center; justify-content: center;
  padding: 12px 20px; border: 0; border-radius: 999px;
  background: var(--accent); color: #080a12;
  font: inherit; font-size: 14px; font-weight: 650; cursor: pointer;
  text-decoration: none; transition: transform 160ms ease, box-shadow 160ms ease;
}
.btn:hover { transform: translateY(-1px); box-shadow: 0 12px 30px hsl(var(--hue) 90% 60% / 0.3); }
.btn.ghost { background: transparent; color: var(--fg); border: 1px solid var(--line); font-weight: 500; }
.note { min-height: 22px; margin-top: 16px; color: var(--accent); font-size: 14px; }
.cards {
  display: grid; grid-template-columns: repeat(auto-fit, minmax(230px, 1fr));
  gap: 14px; max-width: 980px; margin: 0 auto; padding: 40px 24px 100px;
}
.card { padding: 22px; border: 1px solid var(--line); border-radius: 18px; background: rgba(255, 255, 255, 0.035); }
.card h3 { margin: 0 0 8px; font-size: 15px; }
.card p { margin: 0; color: var(--muted); font-size: 13.5px; line-height: 1.65; }
footer { padding: 26px; border-top: 1px solid var(--line); text-align: center; color: var(--muted); font-size: 12.5px; }
@media (prefers-reduced-motion: reduce) { html { scroll-behavior: auto; } .btn { transition: none; } }
`;

  const js = `(function () {
  var cta = document.getElementById("cta");
  var note = document.getElementById("note");
  var KEY = "cygnus-demo-waitlist";

  function joined() {
    note.textContent = "You're on the list — thanks for trying the demo.";
    cta.textContent = "Joined";
    cta.disabled = true;
  }

  try { if (localStorage.getItem(KEY)) joined(); } catch (error) {}

  cta.addEventListener("click", function () {
    try { localStorage.setItem(KEY, new Date().toISOString()); } catch (error) {}
    joined();
  });
})();
`;

  return {
    files: [
      { path: "index.html", content: html },
      { path: "styles.css", content: css },
      { path: "app.js", content: js },
    ],
  };
}
